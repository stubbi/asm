"""Compile and exercise the handwritten world engine on native Apple arm64."""
import pathlib, platform, subprocess, tempfile, unittest
ROOT = pathlib.Path(__file__).resolve().parents[1]
class WorldTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if platform.system() != 'Darwin' or platform.machine() != 'arm64':
            raise unittest.SkipTest('Native Apple arm64 test')
        cls.tmp = tempfile.TemporaryDirectory(prefix='asm-doom-world-')
        cls.exe = pathlib.Path(cls.tmp.name) / 'world-test'
        subprocess.run(['clang','-I',str(ROOT/'src'),'-arch','arm64','-mmacosx-version-min=15.0','-g','-Wall','-Wextra','-Werror',str(ROOT/'tests/world_driver.c'),str(ROOT/'src/world.s'),'-o',str(cls.exe)],check=True)
    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()
    def exercise(self, name):
        result = subprocess.run([str(self.exe), name],timeout=15,capture_output=True,text=True)
        self.assertEqual(result.returncode,0,result.stdout+result.stderr)
